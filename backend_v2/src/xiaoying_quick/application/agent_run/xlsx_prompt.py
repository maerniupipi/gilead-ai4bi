def moc_skill_ids(question: str) -> set[str]:
    picked = {"moc_overview"}
    if any(word in question for word in ("达成", "目标", "缺口", "差额")):
        picked.add("moc_attainment")
    if any(word in question for word in ("同比", "环比", "增长", "增量", "量价", "下滑")):
        picked.add("moc_growth")
    if any(word in question for word in ("结构", "占比", "贡献", "渠道", "城市", "产品", "终端")):
        picked.add("moc_structure")
    if any(word in question for word in ("分析", "诊断", "为什么", "原因", "驱动", "风险", "改善")):
        picked.update(("moc_attainment", "moc_growth", "moc_structure"))
    return picked
