"""Generate fresh-install SQL from application models; never exports runtime data."""

from __future__ import annotations

import argparse
import sqlite3
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend_v2/src"))

from sqlalchemy.dialects import mysql, sqlite  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from xiaoying_quick.infrastructure.chatbots import ChatbotStore  # noqa: E402
from xiaoying_quick.infrastructure.persistence import models as _models  # noqa: E402,F401
from xiaoying_quick.infrastructure.persistence.base import Base  # noqa: E402
from xiaoying_quick.infrastructure.persistence.migration_state import (  # noqa: E402
    expected_migration_heads,
)
from xiaoying_quick.infrastructure.workspace import WorkspaceStore  # noqa: E402


def control_schema(dialect_name: str) -> str:
    dialect = mysql.dialect() if dialect_name == "mysql" else sqlite.dialect()
    lines = [
        "-- Generated by python deploy/generate_sql.py. Fresh EMPTY databases only.",
        "-- Contains schema and migration version only; no users, credentials or business data.",
        "-- Existing installations: run alembic upgrade head instead of importing this file.",
    ]
    if dialect_name == "mysql":
        lines += ["SET NAMES utf8mb4;", "USE `gilead_agent_loop`;"]
    else:
        lines += ["PRAGMA foreign_keys=ON;"]
    for table in Base.metadata.sorted_tables:
        lines.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";")
        for index in sorted(table.indexes, key=lambda item: str(item.name)):
            lines.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
    lines.append("CREATE TABLE alembic_version (version_num VARCHAR(32) NOT NULL PRIMARY KEY);")
    for revision in expected_migration_heads():
        lines.append(f"INSERT INTO alembic_version (version_num) VALUES ('{revision}');")
    return "\n".join(line.rstrip() for line in "\n\n".join(lines).splitlines()) + "\n"


def auxiliary_schema(path: Path) -> str:
    with sqlite3.connect(path) as database:
        rows = database.execute(
            "SELECT sql FROM sqlite_master WHERE type IN ('table','index') AND sql IS NOT NULL "
            "AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, name"
        ).fetchall()
    return (
        "-- Generated schema only. The application seeds its assistant directory at startup.\n"
        "PRAGMA foreign_keys=ON;\n\n"
        + "\n\n".join(str(row[0]).strip().rstrip(";") + ";" for row in rows) + "\n"
    )


def generated_files() -> dict[str, str]:
    files = {
        "mysql/002_control_schema.sql": control_schema("mysql"),
        "sqlite/001_control_schema.sql": control_schema("sqlite"),
    }
    with tempfile.TemporaryDirectory(prefix="gilead-sql-schema-") as directory:
        path = Path(directory)
        ChatbotStore(path / "chatbots.sqlite3", mode="dual")
        WorkspaceStore(path / "workspaces.sqlite3")
        files["sqlite/002_chatbots_schema.sql"] = auxiliary_schema(path / "chatbots.sqlite3")
        files["sqlite/003_workspaces_schema.sql"] = auxiliary_schema(path / "workspaces.sqlite3")
    return files


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if checked-in SQL is outdated")
    args = parser.parse_args()
    for name, contents in generated_files().items():
        target = ROOT / "deploy/sql" / name
        if args.check:
            if not target.is_file() or target.read_text() != contents:
                raise SystemExit(f"SQL is outdated: {name}; run python deploy/generate_sql.py")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(contents)
        print(("checked " if args.check else "wrote ") + name)


if __name__ == "__main__":
    main()
